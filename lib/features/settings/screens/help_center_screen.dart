import 'package:flutter/material.dart';
import 'package:url_launcher/url_launcher.dart';
import '../../../core/constants/app_colors.dart';
import '../../../core/constants/app_constants.dart';
import '../../../shared/widgets/glass_card.dart';

class HelpCenterScreen extends StatelessWidget {
  const HelpCenterScreen({super.key});

  Future<void> _launchUrl(String url) async {
    final uri = Uri.parse(url);
    if (await canLaunchUrl(uri)) {
      await launchUrl(uri, mode: LaunchMode.externalApplication);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: AppColors.darkBackground,
      appBar: AppBar(
        title: const Text('Help Center'),
        leading: const BackButton(color: Colors.white),
      ),
      body: SingleChildScrollView(
        padding: const EdgeInsets.symmetric(horizontal: 20, vertical: 12),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            const Text(
              'Frequently Asked Questions',
              style: TextStyle(fontSize: 16, fontWeight: FontWeight.w800, color: Colors.white),
            ),
            const SizedBox(height: 14),

            _FaqAccordion(
              question: 'How does Puter.js User-Pays AI work?',
              answer:
                  'FoodLens connects to Puter\'s serverless cloud where every user has their own personal account. You get a generous free monthly allowance for AI model runs. When this allowance finishes, you can top up microcredits or upgrade at puter.com/account.',
            ),
            _FaqAccordion(
              question: 'How accurate are the AI calorie estimates?',
              answer:
                  'Estimates are generated by state-of-the-art vision models comparing your plate against validated nutritional databases. While visual recognition is typically 90%+ accurate on standard recipes, hidden oils, sugars, and sauces will vary by chef.',
            ),
            _FaqAccordion(
              question: 'Can I rely on FoodLens for severe allergies?',
              answer:
                  'No. While FoodLens detects probable ingredients and warns of common allergens, an image cannot verify microscopic cross-contamination, cooking oils, or hidden seasonings. Never consume suspect food if you have life-threatening allergies.',
            ),
            _FaqAccordion(
              question: 'Can FoodLens work offline?',
              answer:
                  'Yes! FoodLens retains an offline culinary database of common global dishes. Scans performed offline use local estimation models and sync your history once your connection is restored.',
            ),
            _FaqAccordion(
              question: 'Where can I read the official Puter SDK docs?',
              answer:
                  'Official Puter developer documentation is available at https://docs.puter.com and https://developer.puter.com.',
            ),
            const SizedBox(height: 20),

            // Official links card
            GlassCard(
              padding: const EdgeInsets.all(18),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  const Text('Official Resources', style: TextStyle(fontSize: 14, fontWeight: FontWeight.w700, color: Colors.white)),
                  const SizedBox(height: 10),
                  ListTile(
                    contentPadding: EdgeInsets.zero,
                    title: const Text('Puter Developer Documentation', style: TextStyle(color: AppColors.secondaryLight, fontSize: 13, fontWeight: FontWeight.w600)),
                    trailing: const Icon(Icons.open_in_new, color: AppColors.secondaryLight, size: 18),
                    onTap: () => _launchUrl(AppConstants.puterDocsUrl),
                  ),
                  const Divider(color: AppColors.darkBorder),
                  ListTile(
                    contentPadding: EdgeInsets.zero,
                    title: const Text('Manage Puter Account & Credits', style: TextStyle(color: AppColors.secondaryLight, fontSize: 13, fontWeight: FontWeight.w600)),
                    trailing: const Icon(Icons.open_in_new, color: AppColors.secondaryLight, size: 18),
                    onTap: () => _launchUrl(AppConstants.puterAccountUrl),
                  ),
                ],
              ),
            ),
            const SizedBox(height: 32),
          ],
        ),
      ),
    );
  }
}

class _FaqAccordion extends StatefulWidget {
  final String question;
  final String answer;

  const _FaqAccordion({required this.question, required this.answer});

  @override
  State<_FaqAccordion> createState() => _FaqAccordionState();
}

class _FaqAccordionState extends State<_FaqAccordion> {
  bool _expanded = false;

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 10),
      child: GlassCard(
        padding: const EdgeInsets.all(14),
        onTap: () => setState(() => _expanded = !_expanded),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                Expanded(
                  child: Text(
                    widget.question,
                    style: const TextStyle(fontSize: 13, fontWeight: FontWeight.w700, color: Colors.white),
                  ),
                ),
                Icon(
                  _expanded ? Icons.keyboard_arrow_up : Icons.keyboard_arrow_down,
                  color: AppColors.textMutedDark,
                ),
              ],
            ),
            if (_expanded) ...[
              const SizedBox(height: 8),
              Text(
                widget.answer,
                style: const TextStyle(fontSize: 12, color: AppColors.textSecondaryDark, height: 1.45),
              ),
            ],
          ],
        ),
      ),
    );
  }
}
